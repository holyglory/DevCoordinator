def _resolve_executable(
    argv0: str, *, cwd: Path, environment: Mapping[str, str]
) -> Path:
    if "/" in argv0:
        candidate = Path(argv0)
        if not candidate.is_absolute():
            candidate = cwd / candidate
        try:
            executable = candidate.resolve(strict=True)
        except OSError as error:
            raise TestStoreContractError("test executable is unavailable") from error
    else:
        match = shutil.which(argv0, path=environment.get("PATH"))
        if match is None:
            raise TestStoreContractError("test executable is unavailable")
        executable = Path(match).resolve(strict=True)
    return executable


def _executable_provenance(
    argv0: str, *, cwd: Path, environment: Mapping[str, str]
) -> dict[str, object]:
    executable = _resolve_executable(argv0, cwd=cwd, environment=environment)
    try:
        descriptor = os.open(
            executable, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0)
        )
    except OSError as error:
        raise TestStoreContractError("test executable cannot be observed") from error
    digest = hashlib.sha256()
    observed = 0
    try:
        before = os.fstat(descriptor)
        if not stat.S_ISREG(before.st_mode) or before.st_size > MAX_TOOLCHAIN_BYTES:
            raise TestStoreContractError("test executable provenance is unsafe")
        while True:
            chunk = os.read(descriptor, 1024 * 1024)
            if not chunk:
                break
            observed += len(chunk)
            if observed > MAX_TOOLCHAIN_BYTES:
                raise TestStoreContractError("test executable provenance is unsafe")
            digest.update(chunk)
        after = os.fstat(descriptor)
    finally:
        os.close(descriptor)
    current = executable.lstat()
    if (
        (before.st_dev, before.st_ino, before.st_size)
        != (after.st_dev, after.st_ino, after.st_size)
        or (after.st_dev, after.st_ino, after.st_size)
        != (current.st_dev, current.st_ino, current.st_size)
        or observed != before.st_size
    ):
        raise TestStoreContractError("test executable changed while observed")
    return {
        "name": executable.name,
        "sha256": digest.hexdigest(),
        "size_bytes": observed,
    }


def _version_command(executable: Path, arguments: Sequence[str]) -> tuple[str, ...]:
    try:
        completed = subprocess.run(
            [str(executable), *arguments],
            cwd="/",
            env={
                "PATH": "/usr/local/bin:/usr/bin:/bin",
                "HOME": "/nonexistent",
                "LANG": "C.UTF-8",
                "LC_ALL": "C.UTF-8",
                "PYTEST_DISABLE_PLUGIN_AUTOLOAD": "1",
            },
            stdin=subprocess.DEVNULL,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            timeout=5,
            check=False,
        )
    except (OSError, subprocess.SubprocessError):
        return ()
    payload = completed.stdout[:64 * 1024]
    lines = []
    for raw in payload.decode("utf-8", errors="replace").splitlines()[:256]:
        value = raw.strip()
        if "[" in value:
            value = value.split("[", 1)[0].strip()
        if not value or "]" in value or "/" in value or "\\" in value:
            continue
        if len(value.encode("utf-8")) <= 512:
            lines.append(value)
    return tuple(lines)


def _transitive_toolchain_provenance(
    descriptor: TestAttemptDescriptor,
    *,
    cwd: Path,
    argv: Sequence[str],
    environment: Mapping[str, str],
) -> dict[str, object]:
    executable = _resolve_executable(argv[0], cwd=cwd, environment=environment)
    components: list[dict[str, object]] = []
    complete = descriptor.driver in {"pytest", "node", "dotnet"}
    commands: tuple[tuple[str, tuple[str, ...]], ...]
    if descriptor.driver == "pytest":
        commands = (
            ("python-runtime", ("--version",)),
            ("pytest-runtime", ("-m", "pytest", "--version")),
        )
    elif descriptor.driver == "node":
        commands = (("node-runtime", ("--version",)),)
    elif descriptor.driver == "dotnet":
        commands = (
            ("dotnet-sdk", ("--version",)),
            ("dotnet-runtimes", ("--list-runtimes",)),
            ("dotnet-sdks", ("--list-sdks",)),
        )
    else:
        commands = ()
    for name, arguments in commands:
        values = _version_command(executable, arguments)
        if not values:
            complete = False
        components.append(
            {
                "name": name,
                "arguments": list(arguments),
                "identities": list(values),
                "output_sha256": hashlib.sha256(
                    "\n".join(values).encode("utf-8")
                ).hexdigest(),
            }
        )
    source = dict(descriptor.source_provenance)
    if not source or source.get("complete") is not True:
        complete = False
    return {
        "complete": complete,
        "driver": descriptor.driver,
        "components": components,
        "source": source,
    }


