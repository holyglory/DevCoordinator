def _is_dotnet_project_invocation(descriptor: TestAttemptDescriptor) -> bool:
    return (
        len(descriptor.argv) >= 2
        and (
            descriptor.driver == "dotnet"
            or Path(descriptor.argv[0]).name == "dotnet"
        )
        and descriptor.argv[1] in {"build", "test"}
    )


def _dotnet_locked_restore_required(descriptor: TestAttemptDescriptor) -> bool:
    return descriptor.source_mode == "immutable" and any(
        binding.get("kind") == "dotnet-packages"
        for binding in descriptor.dependency_bindings
    )


def _immutable_python_launch_executable(
    descriptor: TestAttemptDescriptor,
) -> str | None:
    """Return the private mount executable for an external venv toolchain.

    ``argv[0]`` intentionally remains the environment executable so CPython
    discovers the mounted venv and its ``pyvenv.cfg``.  ``Popen.executable``
    selects the same fingerprinted interpreter through the unit-private mount,
    avoiding traversal through an absolute symlink into another local home.
    """

    if descriptor.source_mode != "immutable":
        return None
    for binding in descriptor.dependency_bindings:
        toolchain = binding.get("toolchain")
        if not isinstance(toolchain, Mapping):
            continue
        if toolchain.get("installation_kind") != "python-toolchain":
            continue
        source = Path(str(toolchain["source_root"]))
        resolved = Path(str(toolchain["resolved_executable"]))
        try:
            relative = resolved.relative_to(source)
        except ValueError as error:
            raise TestStoreContractError(
                "immutable Python toolchain executable escapes its root"
            ) from error
        if not relative.parts or any(part in {".", ".."} for part in relative.parts):
            raise TestStoreContractError(
                "immutable Python toolchain executable is invalid"
            )
        return str(_IMMUTABLE_PYTHON_TOOLCHAIN_MOUNT / relative)
    return None


def _dotnet_restore_project(
    argv: Sequence[str], *, cwd: Path, execution_root: Path
) -> Path:
    """Resolve the one typed project operand without leaving the snapshot."""

    if len(argv) < 2 or argv[1] not in {"build", "test"}:
        raise TestStoreContractError(
            "locked dotnet bootstrap requires a dotnet build or test invocation"
        )
    candidates: list[str] = []
    for raw in argv[2:]:
        if raw == "--":
            break
        if raw.startswith("-"):
            continue
        if Path(raw).suffix.lower() in _DOTNET_RESTORE_PROJECT_SUFFIXES:
            candidates.append(raw)
    if len(candidates) != 1:
        raise TestStoreContractError(
            "locked dotnet bootstrap requires exactly one project or solution"
        )
    root = execution_root.resolve(strict=True)
    candidate = Path(candidates[0])
    if not candidate.is_absolute():
        candidate = cwd / candidate
    try:
        before = candidate.lstat()
        resolved = candidate.resolve(strict=True)
        after = candidate.lstat()
    except OSError as error:
        raise TestStoreContractError(
            "locked dotnet project could not be opened safely"
        ) from error
    if (
        stat.S_ISLNK(before.st_mode)
        or not stat.S_ISREG(before.st_mode)
        or _stable_file_identity(before) != _stable_file_identity(after)
        or (resolved != root and root not in resolved.parents)
    ):
        raise TestStoreContractError("locked dotnet project is unsafe")
    return resolved


def _dotnet_restore_semantic_options(argv: Sequence[str]) -> tuple[str, ...]:
    """Retain only bounded graph-selection options; own all source/cache policy."""

    forwarded: list[str] = []
    index = 2
    while index < len(argv) and argv[index] != "--":
        raw = argv[index]
        option_name = raw.split("=", 1)[0].lower()
        if option_name in _DOTNET_RESTORE_OWNED_OPTIONS:
            raise TestStoreContractError(
                "dotnet restore feed and cache options are runner-owned"
            )
        if raw in _DOTNET_RESTORE_VALUE_OPTIONS:
            if (
                index + 1 >= len(argv)
                or argv[index + 1] == "--"
                or argv[index + 1].startswith("-")
            ):
                raise TestStoreContractError(
                    "dotnet restore graph option is missing its value"
                )
            value = argv[index + 1]
            if raw in {"--configuration", "-c"}:
                forwarded.append(f"-p:Configuration={value}")
            elif raw in {"--framework", "-f"}:
                forwarded.append(f"-p:TargetFramework={value}")
            else:
                forwarded.extend((raw, value))
            index += 2
            continue
        if any(
            raw.startswith(option + "=")
            for option in _DOTNET_RESTORE_VALUE_OPTIONS
            if option.startswith("--")
        ):
            if not raw.split("=", 1)[1]:
                raise TestStoreContractError(
                    "dotnet restore graph option is missing its value"
                )
            option, value = raw.split("=", 1)
            if option == "--configuration":
                forwarded.append(f"-p:Configuration={value}")
            elif option == "--framework":
                forwarded.append(f"-p:TargetFramework={value}")
            else:
                forwarded.append(raw)
            index += 1
            continue
        property_prefix = next(
            (
                prefix
                for prefix in ("-p:", "/p:", "--property:")
                if raw.lower().startswith(prefix)
            ),
            None,
        )
        if property_prefix is not None:
            assignment = raw[len(property_prefix) :]
            name, separator, value = assignment.partition("=")
            if name.lower() == "restorelockedmode":
                if separator and value.lower() in {"1", "true"}:
                    index += 1
                    continue
                raise TestStoreContractError(
                    "dotnet locked restore policy is runner-owned"
                )
            if (
                not separator
                or not value
                or name.lower() not in _DOTNET_RESTORE_GRAPH_PROPERTIES
            ):
                raise TestStoreContractError(
                    "dotnet restore MSBuild property is not an allowed graph selector"
                )
            forwarded.append(raw)
        index += 1
    return tuple(forwarded)


def _dotnet_locked_restore_command(
    argv: Sequence[str],
    *,
    cwd: Path,
    execution_root: Path,
    environment: Mapping[str, str],
    packages: Path,
    config_file: Path,
) -> tuple[str, ...]:
    """Build one trusted local-source restore from a typed ``dotnet test`` argv."""

    project = _dotnet_restore_project(argv, cwd=cwd, execution_root=execution_root)
    semantic_options = _dotnet_restore_semantic_options(argv)
    packages_raw = environment.get("NUGET_PACKAGES")
    source_raw = environment.get("DEVCOORDINATOR_NUGET_SOURCE")
    if (
        not packages_raw
        or not source_raw
        or not Path(packages_raw).is_absolute()
        or not Path(source_raw).is_absolute()
    ):
        raise TestStoreContractError("locked dotnet package source is unavailable")
    try:
        resolved_packages = Path(packages_raw).resolve(strict=True)
        resolved_source = Path(source_raw).resolve(strict=True)
        resolved_config = config_file.resolve(strict=True)
        root = execution_root.resolve(strict=True)
    except OSError as error:
        raise TestStoreContractError(
            "locked dotnet package source is unavailable"
        ) from error
    expected_source = root.joinpath(
        *PurePosixPath(_DOTNET_NUGET_SOURCE_DESTINATION).parts
    )
    try:
        source_metadata = Path(source_raw).lstat()
        packages_metadata = packages.lstat()
    except OSError as error:
        raise TestStoreContractError(
            "locked dotnet package source is unavailable"
        ) from error
    if (
        resolved_packages != packages.resolve(strict=True)
        or resolved_packages != packages
        or Path(packages_raw) != packages
        or not stat.S_ISDIR(packages_metadata.st_mode)
        or stat.S_ISLNK(packages_metadata.st_mode)
        or resolved_source != expected_source
        or Path(source_raw) != expected_source
        or not stat.S_ISDIR(source_metadata.st_mode)
        or stat.S_ISLNK(source_metadata.st_mode)
        or next(resolved_source.glob("*/*/*.nupkg"), None) is None
        or resolved_config != config_file
        or not config_file.is_file()
        or config_file.read_text(encoding="utf-8")
        != "<configuration><packageSources><clear /></packageSources></configuration>\n"
    ):
        raise TestStoreContractError("locked dotnet package source is unavailable")
    return (
        argv[0],
        "restore",
        str(project),
        *semantic_options,
        "--locked-mode",
        "--force",
        "--packages",
        str(resolved_packages),
        "--source",
        str(resolved_source),
        "--configfile",
        str(resolved_config),
        "--no-http-cache",
        "--disable-build-servers",
        "-p:NuGetAudit=false",
        "--verbosity",
        "minimal",
    )


def _drain_dotnet_probe_stream(
    stream, state: dict[str, object], *, stream_name: str
) -> None:
    retained = bytearray()
    observed = 0
    while True:
        chunk = stream.read(64 * 1024)
        if not chunk:
            break
        observed += len(chunk)
        if len(retained) < MAX_DOTNET_READINESS_STREAM_BYTES:
            retained.extend(
                chunk[
                    : MAX_DOTNET_READINESS_STREAM_BYTES - len(retained)
                ]
            )
    if observed > len(retained):
        marker = (
            f"\n[DevCoordinator truncated dotnet {stream_name} readiness output; "
            f"observed {observed} bytes]\n"
        ).encode("utf-8")[:MAX_DOTNET_READINESS_STREAM_BYTES]
        keep = max(0, MAX_DOTNET_READINESS_STREAM_BYTES - len(marker))
        retained = retained[:keep] + marker
    state["payload"] = bytes(retained)
    state["observed_bytes"] = observed


def _run_dotnet_probe(
    command: Sequence[str],
    *,
    cwd: Path,
    environment: Mapping[str, str],
    timeout_seconds: float,
) -> DotnetProbeResult:
    """Run a probe while draining both streams without unbounded buffering."""

    process = subprocess.Popen(
        list(command),
        cwd=cwd,
        env=dict(environment),
        stdin=subprocess.DEVNULL,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        start_new_session=True,
    )
    if process.stdout is None or process.stderr is None:
        process.kill()
        process.wait()
        raise subprocess.SubprocessError("dotnet readiness pipes are unavailable")
    stdout_state: dict[str, object] = {}
    stderr_state: dict[str, object] = {}
    threads = (
        threading.Thread(
            target=_drain_dotnet_probe_stream,
            args=(process.stdout, stdout_state),
            kwargs={"stream_name": "stdout"},
        ),
        threading.Thread(
            target=_drain_dotnet_probe_stream,
            args=(process.stderr, stderr_state),
            kwargs={"stream_name": "stderr"},
        ),
    )
    for thread in threads:
        thread.start()
    timed_out = False
    try:
        returncode = process.wait(timeout=timeout_seconds)
    except subprocess.TimeoutExpired:
        timed_out = True
        try:
            os.killpg(process.pid, signal.SIGKILL)
        except ProcessLookupError:
            process.kill()
        returncode = process.wait()
    else:
        try:
            os.killpg(process.pid, signal.SIGKILL)
        except ProcessLookupError:
            pass
    for thread in threads:
        thread.join()
    process.stdout.close()
    process.stderr.close()
    return DotnetProbeResult(
        124 if timed_out else int(returncode),
        bytes(stdout_state.get("payload", b"")),
        bytes(stderr_state.get("payload", b"")),
        timed_out,
    )


def _dotnet_global_json(
    argv: Sequence[str], *, cwd: Path, execution_root: Path
) -> Path | None:
    """Resolve the SDK policy nearest the declared project, within the snapshot."""

    root = execution_root.resolve(strict=True)
    starts: list[Path] = []
    for raw in argv[1:]:
        if not raw or raw.startswith("-"):
            continue
        candidate = Path(raw)
        if not candidate.is_absolute():
            candidate = cwd / candidate
        try:
            resolved = candidate.resolve(strict=True)
        except OSError:
            continue
        if resolved != root and root not in resolved.parents:
            continue
        if resolved.is_dir() or resolved.suffix.lower() in _DOTNET_PROJECT_SUFFIXES:
            starts.append(resolved if resolved.is_dir() else resolved.parent)
            break
    starts.append(cwd)
    for start in starts:
        for directory in (start, *start.parents):
            if directory != root and root not in directory.parents:
                break
            candidate = directory / "global.json"
            if candidate.is_file():
                return candidate
            if directory == root:
                break
    return None


def _dotnet_sdk_version(global_json: Path | None) -> str | None:
    if global_json is None:
        return None
    try:
        metadata = global_json.stat()
        if metadata.st_size > MAX_DOTNET_GLOBAL_JSON_BYTES:
            return None
        document = json.loads(global_json.read_bytes())
    except (OSError, ValueError):
        return None
    if not isinstance(document, Mapping) or not isinstance(document.get("sdk"), Mapping):
        return None
    version = document["sdk"].get("version")
    return version if isinstance(version, str) and 0 < len(version) <= 128 else None


def _dotnet_readiness(
    argv: Sequence[str],
    *,
    cwd: Path,
    execution_root: Path,
    environment: Mapping[str, str],
    timeout_seconds: int,
    locked_restore: bool = False,
    output: Path | None = None,
    deadline: float | None = None,
) -> DotnetReadinessFailure | None:
    """Validate SDK selection and trusted restore before project execution."""

    global_json = _dotnet_global_json(argv, cwd=cwd, execution_root=execution_root)
    sdk_version = _dotnet_sdk_version(global_json)
    readiness_cwd = global_json.parent if global_json is not None else cwd
    deadline = (
        time.monotonic() + timeout_seconds if deadline is None else deadline
    )
    probes: tuple[tuple[str, tuple[str, ...], Path], ...] = (
        ("sdk", (argv[0], "--version"), readiness_cwd),
    )
    if locked_restore:
        try:
            if output is None:
                raise TestStoreContractError(
                    "locked dotnet bootstrap output is unavailable"
                )
            packages = output / "nuget-packages"
            try:
                packages.mkdir(mode=0o700)
            except FileExistsError:
                metadata = packages.lstat()
                if stat.S_ISLNK(metadata.st_mode) or not stat.S_ISDIR(metadata.st_mode):
                    raise TestStoreContractError(
                        "locked dotnet writable package cache is unsafe"
                    )
            if any(packages.iterdir()):
                raise TestStoreContractError(
                    "locked dotnet writable package cache is not empty"
                )
            environment["NUGET_PACKAGES"] = str(packages)
            config_file = output / "NuGet.Config"
            try:
                config_file.write_text(
                    "<configuration><packageSources><clear /></packageSources>"
                    "</configuration>\n",
                    encoding="utf-8",
                )
                config_file.chmod(0o600)
            except OSError as error:
                raise TestStoreContractError(
                    "locked dotnet source configuration is unavailable"
                ) from error
            restore = _dotnet_locked_restore_command(
                argv,
                cwd=cwd,
                execution_root=execution_root,
                environment=environment,
                packages=packages,
                config_file=config_file,
            )
        except (OSError, TestStoreContractError) as error:
            detail = (" ".join(str(error).split()) or type(error).__name__)[:2048]
            return DotnetReadinessFailure(
                "restore",
                127,
                b"",
                (
                    "DevCoordinator could not prepare the trusted offline "
                    f"dotnet restore ({type(error).__name__}): {detail}\n"
                ).encode("utf-8", errors="replace"),
                global_json,
                sdk_version,
                False,
            )
        probes += (("restore", restore, cwd),)
    for stage, command, probe_cwd in probes:
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            return DotnetReadinessFailure(
                stage,
                124,
                b"",
                (
                    "DevCoordinator dotnet readiness exhausted the caller's "
                    f"{timeout_seconds}s execution timeout before project tests.\n"
                ).encode("utf-8"),
                global_json,
                sdk_version,
                False,
            )
        try:
            completed = _run_dotnet_probe(
                command,
                cwd=probe_cwd,
                environment=environment,
                timeout_seconds=remaining,
            )
        except (OSError, subprocess.SubprocessError) as error:
            detail = (" ".join(str(error).split()) or type(error).__name__)[:2048]
            return DotnetReadinessFailure(
                stage,
                127,
                b"",
                (
                    "DevCoordinator could not start dotnet readiness "
                    f"({type(error).__name__}): {detail}\n"
                ).encode("utf-8", errors="replace"),
                global_json,
                sdk_version,
                False,
            )
        if completed.timed_out:
            stderr = completed.stderr + (
                "DevCoordinator dotnet readiness exhausted the caller's "
                f"{timeout_seconds}s execution timeout before project tests.\n"
            ).encode("utf-8")
            return DotnetReadinessFailure(
                stage,
                124,
                completed.stdout,
                stderr,
                global_json,
                sdk_version,
                False,
            )
        if completed.returncode != 0:
            combined = completed.stdout + b"\n" + completed.stderr
            unavailable = stage == "sdk" and (
                b"compatible .NET SDK was not found" in combined
                or b"Requested SDK version:" in combined
            )
            return DotnetReadinessFailure(
                stage,
                int(completed.returncode),
                completed.stdout,
                completed.stderr,
                global_json,
                sdk_version,
                unavailable,
            )
    return None


def _jsonl_cases(path: Path) -> tuple[list[dict[str, object]], list[dict[str, object]]]:
    if path.stat().st_size > MAX_REPORT_BYTES:
        raise TestStoreContractError("JSONL reporter output exceeds its bound")
    cases: list[dict[str, object]] = []
    failures: list[dict[str, object]] = []
    with path.open("r", encoding="utf-8", errors="strict") as stream:
        for index, line in enumerate(stream):
            if index >= MAX_CASES or len(line.encode("utf-8")) > 1024 * 1024:
                raise TestStoreContractError("JSONL reporter output is excessive")
            value = json.loads(line)
            if not isinstance(value, Mapping):
                raise TestStoreContractError("JSONL reporter event is invalid")
            raw_status = str(value.get("status") or value.get("outcome") or "")
            status = {
                "pass": "passed", "passed": "passed", "ok": "passed",
                "fail": "failed", "failed": "failed",
                "skip": "skipped", "skipped": "skipped",
                "error": "error",
            }.get(raw_status.lower())
            if status is None:
                continue
            case_id = str(value.get("case_id") or value.get("id") or f"case-{index}")[:1024]
            display = str(value.get("name") or value.get("display_name") or case_id)[:4096]
            duration = value.get("duration_seconds", value.get("duration", 0.0))
            if isinstance(duration, bool) or not isinstance(duration, (int, float)) or duration < 0:
                duration = 0.0
            case = {
                "case_id": case_id,
                "display_name": display,
                "status": status,
                "duration_seconds": float(duration),
                "location": None if value.get("location") is None else str(value["location"])[:4096],
            }
            cases.append(case)
            if status in {"failed", "error"}:
                failures.append(
                    {
                        "failure_id": "failure-" + hashlib.sha256(
                            f"{index}\0{case_id}".encode("utf-8")
                        ).hexdigest()[:32],
                        "classification": "test_failure",
                        "message": str(value.get("message") or display)[:8192],
                        "case_id": case_id,
                        "location": case["location"],
                        "artifact_id": None,
                    }
                )
    return cases, failures


def _trx_cases(path: Path) -> tuple[list[dict[str, object]], list[dict[str, object]]]:
    if path.stat().st_size > MAX_REPORT_BYTES:
        raise TestStoreContractError("TRX reporter output exceeds its bound")
    root = ET.parse(path).getroot()
    cases: list[dict[str, object]] = []
    failures: list[dict[str, object]] = []
    for index, element in enumerate(root.iter()):
        if index > MAX_CASES * 8:
            raise TestStoreContractError("TRX reporter output is excessive")
        if element.tag.rsplit("}", 1)[-1] != "UnitTestResult":
            continue
        outcome = str(element.attrib.get("outcome", "")).lower()
        status = {
            "passed": "passed", "failed": "failed", "notexecuted": "skipped",
            "inconclusive": "skipped", "error": "error",
        }.get(outcome, "error")
        case_id = str(element.attrib.get("testId") or f"trx-{len(cases)}")[:1024]
        display = str(element.attrib.get("testName") or case_id)[:4096]
        duration_text = str(element.attrib.get("duration") or "")
        duration = 0.0
        matched_duration = re.fullmatch(
            r"(?:(\d+)\.)?(\d+):(\d+):([0-9]+(?:\.[0-9]+)?)",
            duration_text,
        )
        if matched_duration is not None:
            days, hours, minutes, seconds = matched_duration.groups()
            duration = (
                int(days or 0) * 86_400
                + int(hours) * 3_600
                + int(minutes) * 60
                + float(seconds)
            )
        cases.append(
            {
                "case_id": case_id,
                "display_name": display,
                "status": status,
                "duration_seconds": duration,
                "location": None,
            }
        )
        if status in {"failed", "error"}:
            failures.append(
                {
                    "failure_id": "failure-" + hashlib.sha256(case_id.encode()).hexdigest()[:32],
                    "classification": "test_failure",
                    "message": display,
                    "case_id": case_id,
                    "location": None,
                    "artifact_id": None,
                }
            )
    return cases, failures


def _junit_cases(path: Path) -> tuple[list[dict[str, object]], list[dict[str, object]]]:
    if path.stat().st_size > MAX_REPORT_BYTES:
        raise TestStoreContractError("JUnit reporter output exceeds its bound")
    root = ET.parse(path).getroot()
    cases: list[dict[str, object]] = []
    failures: list[dict[str, object]] = []
    for element in root.iter():
        if element.tag.rsplit("}", 1)[-1] != "testcase":
            continue
        if len(cases) >= MAX_CASES:
            raise TestStoreContractError("JUnit reporter output is excessive")
        child_kinds = {child.tag.rsplit("}", 1)[-1] for child in element}
        status = (
            "error" if "error" in child_kinds else
            "failed" if "failure" in child_kinds else
            "skipped" if "skipped" in child_kinds else
            "passed"
        )
        display = str(element.attrib.get("name") or f"case-{len(cases)}")[:4096]
        classname = str(element.attrib.get("classname") or "")
        case_id = hashlib.sha256(
            f"{classname}\0{display}\0{len(cases)}".encode("utf-8")
        ).hexdigest()
        try:
            duration = max(0.0, float(element.attrib.get("time", "0")))
        except ValueError:
            duration = 0.0
        case = {
            "case_id": "case-" + case_id[:32],
            "display_name": display,
            "status": status,
            "duration_seconds": duration,
            "location": classname[:4096] or None,
        }
        cases.append(case)
        if status in {"failed", "error"} and len(failures) < MAX_FAILURES:
            detail = next(
                (
                    (child.text or child.attrib.get("message") or display)
                    for child in element
                    if child.tag.rsplit("}", 1)[-1] in {"failure", "error"}
                ),
                display,
            )
            failures.append(
                {
                    "failure_id": "failure-" + case_id[:32],
                    "classification": "test_failure",
                    "message": str(detail)[:8192],
                    "case_id": case["case_id"],
                    "location": case["location"],
                    "artifact_id": None,
                }
            )
    return cases, failures


def _result_chunks(
    descriptor: TestAttemptDescriptor,
    *,
    cases: Sequence[Mapping[str, object]],
    failures: Sequence[Mapping[str, object]],
    artifacts: Sequence[Mapping[str, object]],
    reporter_complete: bool,
) -> tuple[dict[str, object], ...]:
    """Partition reporter output into independently bounded store chunks."""

    limits = {"cases": 500, "failures": 64, "artifacts": 64}
    chunks: list[dict[str, object]] = []
    current: dict[str, object] = {
        "cases": [],
        "failures": [],
        "artifacts": [],
    }

    def encoded_size(value: Mapping[str, object]) -> int:
        probe = {
            "chunk_id": "chunk-" + "0" * 32,
            "chunk_index": len(chunks),
            "cases": value["cases"],
            "failures": value["failures"],
            "artifacts": value["artifacts"],
            "reporter_complete": False,
        }
        return len(_json_bytes(probe, maximum=MAX_RESULT_CHUNK_BYTES + 1))

    def flush() -> None:
        nonlocal current
        if not any(current[name] for name in ("cases", "failures", "artifacts")):
            return
        if len(chunks) >= MAX_RESULT_CHUNKS:
            raise TestStoreContractError("runner produced too many result chunks")
        chunks.append(current)
        current = {"cases": [], "failures": [], "artifacts": []}

    for field, values in (
        ("artifacts", artifacts),
        ("failures", failures),
        ("cases", cases),
    ):
        for raw in values:
            collection = current[field]
            if not isinstance(collection, list):
                raise TestStoreContractError("runner result chunk accumulator is invalid")
            collection.append(dict(raw))
            try:
                excessive = len(collection) > limits[field] or encoded_size(current) > MAX_RESULT_CHUNK_BYTES
            except TestStoreContractError:
                excessive = True
            if excessive:
                collection.pop()
                flush()
                replacement = current[field]
                if not isinstance(replacement, list):
                    raise TestStoreContractError(
                        "runner result chunk accumulator is invalid"
                    )
                replacement.append(dict(raw))
                if encoded_size(current) > MAX_RESULT_CHUNK_BYTES:
                    raise TestStoreContractError(
                        f"single runner {field[:-1]} exceeds the result chunk bound"
                    )
    flush()
    if not chunks:
        chunks.append({"cases": [], "failures": [], "artifacts": []})
    normalized: list[dict[str, object]] = []
    for index, values in enumerate(chunks):
        identity = hashlib.sha256(
            (
                descriptor.attempt_id
                + "\0"
                + str(descriptor.generation)
                + "\0"
                + str(index)
            ).encode("utf-8")
        ).hexdigest()[:32]
        normalized.append(
            {
                "chunk_id": "chunk-" + identity,
                "chunk_index": index,
                "cases": values["cases"],
                "failures": values["failures"],
                "artifacts": values["artifacts"],
                "reporter_complete": reporter_complete and index == len(chunks) - 1,
            }
        )
    return tuple(normalized)


def _write_result_chunks(
    output: Path, chunks: Sequence[Mapping[str, object]]
) -> list[dict[str, object]]:
    manifest: list[dict[str, object]] = []
    for index, chunk in enumerate(chunks):
        if chunk.get("chunk_index") != index:
            raise TestStoreContractError("runner result chunk ordering is invalid")
        payload = _json_bytes(chunk, maximum=MAX_RESULT_CHUNK_BYTES)
        name = f"result-chunk-{index:06d}.json"
        path = output / name
        descriptor_fd = os.open(
            path,
            os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0),
            0o600,
        )
        try:
            _write_all(descriptor_fd, payload)
            os.fsync(descriptor_fd)
        finally:
            os.close(descriptor_fd)
        manifest.append(
            {
                "chunk_id": chunk["chunk_id"],
                "chunk_index": index,
                "file_name": name,
                "sha256": hashlib.sha256(payload).hexdigest(),
                "size_bytes": len(payload),
                "reporter_complete": chunk["reporter_complete"],
            }
        )
    return manifest


def _terminal_outcome(
    *,
    returncode: int,
    incomplete_reporting: bool,
    failures: Sequence[Mapping[str, object]],
) -> str:
    """Classify trusted runner completion independently of process exit code."""

    classifications = {str(item.get("classification")) for item in failures}
    if incomplete_reporting:
        return "incomplete"
    if "timeout" in classifications:
        return "timed_out"
    if "infrastructure_failure" in classifications:
        return "infrastructure_failed"
    if "test_failure" in classifications or returncode != 0:
        return "test_failed"
    return "succeeded"


def run(
    descriptor: TestAttemptDescriptor, output: Path, result_path: Path
) -> int:
    global _EXACT_SECRET_VARIANTS
    _EXACT_SECRET_VARIANTS = _credential_secret_variants(descriptor)
    root = Path(descriptor.execution_root)
    cwd = (root / descriptor.cwd).resolve(strict=True)
    if root != cwd and root not in cwd.parents:
        raise TestStoreContractError("runner cwd escapes attempt root")
    stdout_path = output / f"{descriptor.attempt_id}-stdout.log"
    stderr_path = output / f"{descriptor.attempt_id}-stderr.log"
    for path in (stdout_path, stderr_path, result_path):
        path.unlink(missing_ok=True)
    adapted_argv, adapted_environment, generated_reporter, generated_kind = (
        adapt_driver_invocation(descriptor, output)
    )
    environment = {
        "PATH": "/usr/local/bin:/usr/bin:/bin",
        "HOME": str(output / "home"),
        "LANG": "C.UTF-8",
        "LC_ALL": "C.UTF-8",
        **adapted_environment,
    }
    # Some cross-platform tests need a short canonical scratch base (notably
    # for AF_UNIX) and cannot use the account database home hidden by the
    # native sandbox. Linux attempts receive a unit-private /tmp namespace;
    # test-created directories remain 0700 on other platforms.
    environment["DEVCOORDINATOR_TEST_TMP_ROOT"] = "/tmp"
    python_launch_executable = _immutable_python_launch_executable(descriptor)
    if python_launch_executable is not None:
        environment["PYTHONHOME"] = str(_IMMUTABLE_PYTHON_TOOLCHAIN_MOUNT)
    credential_directory = os.environ.get("CREDENTIALS_DIRECTORY")
    if descriptor.fixtures:
        if not credential_directory or not Path(credential_directory).is_absolute():
            raise TestStoreContractError("test fixture credentials are unavailable")
        environment["DEVCOORDINATOR_FIXTURE_DIRECTORY"] = credential_directory
        # Fixture consumers use the standard systemd credentials contract for
        # both the public fixture catalog and any broker-issued secret files.
        # The compatibility alias above remains for older harness adapters.
        environment["CREDENTIALS_DIRECTORY"] = credential_directory
    if descriptor.credentials:
        if not credential_directory or not Path(credential_directory).is_absolute():
            raise TestStoreContractError(
                "operational credential directory is unavailable"
            )
        environment["CREDENTIALS_DIRECTORY"] = credential_directory
    Path(environment["HOME"]).mkdir(mode=0o700, exist_ok=True)
    is_dotnet_invocation = _is_dotnet_project_invocation(descriptor)
    if is_dotnet_invocation:
        Path(environment["DOTNET_CLI_HOME"]).mkdir(mode=0o700, exist_ok=True)
    started = time.monotonic()
    deadline = started + descriptor.ttl_seconds
    usage_before = resource.getrusage(resource.RUSAGE_CHILDREN)
    stdout_state: dict[str, object] = {}
    stderr_state: dict[str, object] = {}
    launch_error: OSError | subprocess.SubprocessError | None = None
    readiness_failure: DotnetReadinessFailure | None = None
    project_execution_started = False
    project_timed_out = False
    try:
        readiness_failure = (
            _dotnet_readiness(
                adapted_argv,
                cwd=cwd,
                execution_root=root,
                environment=environment,
                timeout_seconds=descriptor.ttl_seconds,
                locked_restore=_dotnet_locked_restore_required(descriptor),
                output=output,
                deadline=deadline,
            )
            if is_dotnet_invocation
            else None
        )
        if readiness_failure is not None:
            returncode = readiness_failure.returncode
            _capture(io.BytesIO(readiness_failure.stdout), stdout_path, stdout_state)
            _capture(io.BytesIO(readiness_failure.stderr), stderr_path, stderr_state)
        else:
            process = subprocess.Popen(
                list(adapted_argv),
                executable=python_launch_executable,
                cwd=cwd,
                env=environment,
                stdin=subprocess.DEVNULL,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                start_new_session=True,
            )
            project_execution_started = True
            if process.stdout is None or process.stderr is None:
                process.kill()
                process.wait()
                raise TestStoreContractError("runner capture pipes are unavailable")
            threads = [
                threading.Thread(
                    target=_capture,
                    args=(process.stdout, stdout_path, stdout_state),
                ),
                threading.Thread(
                    target=_capture,
                    args=(process.stderr, stderr_path, stderr_state),
                ),
            ]
            for thread in threads:
                thread.start()
            remaining = deadline - time.monotonic()
            try:
                returncode = process.wait(timeout=max(0.0, remaining))
            except subprocess.TimeoutExpired:
                project_timed_out = True
                try:
                    os.killpg(process.pid, signal.SIGKILL)
                except ProcessLookupError:
                    process.kill()
                process.wait()
                returncode = 124
            else:
                try:
                    os.killpg(process.pid, signal.SIGKILL)
                except ProcessLookupError:
                    pass
            for thread in threads:
                thread.join()
            process.stdout.close()
            process.stderr.close()
    except (OSError, subprocess.SubprocessError) as error:
        launch_error = error
        returncode = 127
        detail = (" ".join(str(error).split()) or type(error).__name__)[:2048]
        _capture(io.BytesIO(b""), stdout_path, stdout_state)
        _capture(
            io.BytesIO(
                (
                    "DevCoordinator could not start the declared test process "
                    f"({type(error).__name__}): {detail}\n"
                ).encode("utf-8", errors="replace")
            ),
            stderr_path,
            stderr_state,
        )
    usage_after = resource.getrusage(resource.RUSAGE_CHILDREN)
    cpu_seconds = max(
        0.0,
        float(usage_after.ru_utime + usage_after.ru_stime)
        - float(usage_before.ru_utime + usage_before.ru_stime),
    )
    # Linux reports ru_maxrss in KiB. The runner has exactly one test child;
    # this provides durable best-effort evidence when systemd has already
    # collected the transient unit before the authority observes it.
    raw_peak_memory = int(usage_after.ru_maxrss)
    peak_memory_bytes = (
        raw_peak_memory * (1024 if sys.platform.startswith("linux") else 1)
        if raw_peak_memory > 0
        else None
    )
    _redact_capture_if_needed(stdout_path, stdout_state)
    _redact_capture_if_needed(stderr_path, stderr_state)
    secret_leak = bool(stdout_state.get("secret_redacted")) or bool(
        stderr_state.get("secret_redacted")
    )
    if secret_leak:
        returncode = 1
    duration = max(0.0, time.monotonic() - started)
    stdout_artifact = _capture_artifact(
        descriptor,
        stream_name="stdout",
        path=stdout_path,
        state=stdout_state,
    )
    stderr_artifact = _capture_artifact(
        descriptor,
        stream_name="stderr",
        path=stderr_path,
        state=stderr_state,
    )
    artifacts: list[Mapping[str, object]] = [stdout_artifact, stderr_artifact]
    reporter_path: Path | None = None
    # A trusted readiness/bootstrap result is itself complete evidence.  It did
    # not start the project reporter, so it must not be mislabeled as an
    # incomplete test report.
    incomplete = secret_leak or launch_error is not None
    failures: list[dict[str, object]] = []
    if launch_error is not None:
        failures.append(
            {
                "failure_id": "failure-" + hashlib.sha256(
                    (
                        descriptor.attempt_id
                        + "\0process-launch\0"
                        + type(launch_error).__name__
                        + "\0"
                        + (" ".join(str(launch_error).split())[:2048])
                    ).encode("utf-8")
                ).hexdigest()[:32],
                "classification": "infrastructure_failure",
                "message": (
                    "The declared test process could not be started "
                    f"({type(launch_error).__name__}); inspect the linked "
                    "bounded runner log"
                )[:8192],
                "case_id": None,
                "location": "runner/bootstrap",
                "artifact_id": stderr_artifact["artifact_id"],
            }
        )
    if readiness_failure is not None:
        evidence = (
            stderr_artifact
            if int(stderr_state.get("observed_bytes", 0)) > 0
            else stdout_artifact
        )
        global_json_label: str | None = None
        if readiness_failure.global_json is not None:
            try:
                global_json_label = readiness_failure.global_json.relative_to(
                    root
                ).as_posix()
            except ValueError:
                global_json_label = readiness_failure.global_json.name
        readiness_payload = (
            readiness_failure.stdout + b"\n" + readiness_failure.stderr
        ).upper()
        locked_graph_mismatch = (
            readiness_failure.stage == "restore"
            and (b"NU1004" in readiness_payload or b"NU1005" in readiness_payload)
        )
        if returncode == 124:
            classification = "timeout"
            message = (
                f"The trusted dotnet {readiness_failure.stage} timed out; "
                "inspect the linked bounded bootstrap log"
            )
        elif locked_graph_mismatch:
            classification = "test_failure"
            message = (
                "The project dependency graph does not match its locked restore "
                "contract; update the lock file and inspect the linked bounded log"
            )
        elif readiness_failure.sdk_unavailable:
            classification = "infrastructure_failure"
            subject = (
                f"The requested dotnet SDK {readiness_failure.sdk_version}"
                if readiness_failure.sdk_version is not None
                else "The requested dotnet SDK"
            )
            context = (
                f" from {global_json_label}"
                if global_json_label is not None
                else ""
            )
            message = (
                f"{subject}{context} is unavailable (exit status {returncode}); "
                "inspect the linked bounded SDK log"
            )
        elif readiness_failure.stage == "sdk":
            classification = "infrastructure_failure"
            message = (
                "The dotnet SDK failed selection/bootstrap readiness "
                f"(exit status {returncode}); inspect the linked bounded SDK log"
            )
        elif readiness_failure.stage == "restore":
            classification = "infrastructure_failure"
            message = (
                "The runner-owned offline locked dotnet restore failed "
                f"(exit status {returncode}); inspect the linked bounded bootstrap log"
            )
        else:
            classification = "infrastructure_failure"
            sdk_label = (
                f" for SDK {readiness_failure.sdk_version}"
                if readiness_failure.sdk_version is not None
                else ""
            )
            message = (
                f"The dotnet workload/bootstrap readiness{sdk_label} failed "
                f"(exit status {returncode}); inspect the linked bounded SDK log"
            )
        failures.append(
            {
                "failure_id": "failure-" + hashlib.sha256(
                    (
                        descriptor.attempt_id
                        + "\0dotnet-readiness\0"
                        + readiness_failure.stage
                        + "\0"
                        + str(returncode)
                    ).encode("utf-8")
                ).hexdigest()[:32],
                "classification": classification,
                "message": message[:8192],
                "case_id": None,
                "location": (
                    "setup/dotnet-lock"
                    if locked_graph_mismatch
                    else (
                        "runner/dotnet-bootstrap"
                        if readiness_failure.stage == "restore"
                        else "runner/dotnet-readiness"
                    )
                ),
                "artifact_id": evidence["artifact_id"],
            }
        )
    if project_timed_out:
        evidence = (
            stderr_artifact
            if int(stderr_state.get("observed_bytes", 0)) > 0
            else stdout_artifact
        )
        failures.append(
            {
                "failure_id": "failure-" + hashlib.sha256(
                    (descriptor.attempt_id + "\0project-timeout").encode("utf-8")
                ).hexdigest()[:32],
                "classification": "timeout",
                "message": (
                    "The declared test process exceeded the caller-selected "
                    f"{descriptor.ttl_seconds}s execution deadline; inspect "
                    "the linked bounded process log"
                ),
                "case_id": None,
                "location": "runner/execution",
                "artifact_id": evidence["artifact_id"],
            }
        )
    if secret_leak:
        failures.append(
            {
                "failure_id": "failure-" + uuid.uuid4().hex,
                "classification": "infrastructure_failure",
                "message": "test output contained protected credential material",
                "case_id": None,
                "location": None,
                "artifact_id": None,
            }
        )
    cases: list[dict[str, object]] = []
    if (
        launch_error is None
        and readiness_failure is None
        and not project_timed_out
    ):
        try:
            provenance_path = _write_execution_provenance(
                descriptor,
                output=output,
                cwd=cwd,
                argv=adapted_argv,
                environment=environment,
            )
            artifacts.append(
                _generated_artifact(
                    descriptor,
                    provenance_path,
                    kind="trace",
                    name="execution-provenance",
                )
            )
        except TestStoreContractError as error:
            incomplete = True
            failures.append(
                {
                    "failure_id": "failure-" + uuid.uuid4().hex,
                    "classification": "infrastructure_failure",
                    "message": str(error)[:8192],
                    "case_id": None,
                    "location": None,
                    "artifact_id": None,
                }
            )
    for policy in descriptor.artifacts:
        try:
            value = _artifact(descriptor, root, output, policy)
            if value is not None:
                artifacts.append(value)
                if (
                    reporter_path is None
                    and policy["kind"] in {"jsonl", "trx", "junit"}
                ):
                    reporter_path = Path(str(value["_source_path"]))
        except TestStoreContractError as error:
            incomplete = True
            failures.append(
                {
                    "failure_id": "failure-" + uuid.uuid4().hex,
                    "classification": "incomplete_reporting",
                    "message": str(error)[:8192],
                    "case_id": None,
                    "location": None,
                    "artifact_id": None,
                }
            )
    failure_diagnostic_artifact: Mapping[str, object] | None = None
    if returncode != 0 and launch_error is None and not project_timed_out:
        failure_diagnostic_artifact = _directory_failure_diagnostic(
            descriptor,
            artifacts,
            output=output,
        )
        if failure_diagnostic_artifact is not None:
            artifacts.append(failure_diagnostic_artifact)
    if len(artifacts) > MAX_ARTIFACTS:
        incomplete = True
        artifacts = artifacts[:MAX_ARTIFACTS]
    if generated_reporter.exists():
        try:
            generated = _generated_artifact(
                descriptor,
                generated_reporter,
                kind=generated_kind,
                name="coordinator-reporter",
            )
            artifacts.append(generated)
            reporter_path = generated_reporter
        except TestStoreContractError as error:
            incomplete = True
            failures.append(
                {
                    "failure_id": "failure-" + uuid.uuid4().hex,
                    "classification": "incomplete_reporting",
                    "message": str(error)[:8192],
                    "case_id": None,
                    "location": None,
                    "artifact_id": None,
                }
            )
    elif (
        descriptor.driver == "automation"
        and launch_error is None
        and not project_timed_out
    ):
        # Automation adapters may wrap compound repository checks.  Preserve
        # one explicit target-level case when the script has no case stream;
        # other typed drivers must publish their injected reporter.
        cases = [
            {
                "case_id": "case-" + hashlib.sha256(
                    descriptor.attempt_id.encode("utf-8")
                ).hexdigest()[:32],
                "display_name": descriptor.target_name,
                "status": "passed" if returncode == 0 else "failed",
                "duration_seconds": duration,
                "location": None,
            }
        ]
    elif (
        launch_error is None
        and readiness_failure is None
        and not project_timed_out
    ):
        incomplete = True
        failures.append(
            {
                "failure_id": "failure-" + uuid.uuid4().hex,
                "classification": "incomplete_reporting",
                "message": f"{descriptor.driver} reporter output was not produced",
                "case_id": None,
                "location": None,
                "artifact_id": None,
            }
        )
    if reporter_path is not None:
        try:
            if generated_kind == "trx" or descriptor.reporter == "trx":
                cases, reporter_failures = _trx_cases(reporter_path)
            elif generated_kind == "junit":
                cases, reporter_failures = _junit_cases(reporter_path)
            else:
                cases, reporter_failures = _jsonl_cases(reporter_path)
            failures.extend(reporter_failures)
        except Exception as error:
            incomplete = True
            failures.append(
                {
                    "failure_id": "failure-" + uuid.uuid4().hex,
                    "classification": "incomplete_reporting",
                    "message": f"reporter output is invalid: {type(error).__name__}",
                    "case_id": None,
                    "location": None,
                    "artifact_id": None,
                }
            )
    if (
        project_execution_started
        and not project_timed_out
        and returncode != 0
        and not any(
            failure["classification"] == "test_failure" for failure in failures
        )
    ):
        # A process exit is still actionable even when an automation reporter
        # produced no failing case (or failed before it could do so).  Link the
        # concise failure to bounded evidence without copying arbitrary project
        # output into the agent summary.
        evidence = failure_diagnostic_artifact or (
            stderr_artifact
            if int(stderr_state.get("observed_bytes", 0)) > 0
            else stdout_artifact
        )
        failures.append(
            {
                "failure_id": "failure-" + hashlib.sha256(
                    (
                        descriptor.attempt_id
                        + "\0process-exit\0"
                        + str(returncode)
                    ).encode("utf-8")
                ).hexdigest()[:32],
                "classification": "test_failure",
                "message": (
                    f"{descriptor.target_name} exited with status {returncode}; "
                    "inspect the linked bounded process log"
                )[:8192],
                "case_id": None,
                "location": None,
                "artifact_id": evidence["artifact_id"],
            }
        )
    failures = failures[:MAX_FAILURES]
    artifacts = artifacts[:MAX_ARTIFACTS]
    artifacts, artifact_sources = _artifact_sources(
        artifacts,
        output=output,
        execution_root=root,
    )
    chunks = _result_chunks(
        descriptor,
        cases=cases,
        failures=failures,
        artifacts=artifacts,
        reporter_complete=not incomplete,
    )
    chunk_manifest = _write_result_chunks(output, chunks)
    public_stdout_state = {
        key: value for key, value in stdout_state.items() if not key.startswith("_")
    }
    public_stderr_state = {
        key: value for key, value in stderr_state.items() if not key.startswith("_")
    }
    for state in (stdout_state, stderr_state):
        descriptor_fd = state.pop("_descriptor", None)
        if type(descriptor_fd) is int:
            os.close(descriptor_fd)
    terminal_outcome = _terminal_outcome(
        returncode=returncode,
        incomplete_reporting=incomplete,
        failures=failures,
    )
    result = {
        "schema_version": 3,
        "attempt_id": descriptor.attempt_id,
        "generation": descriptor.generation,
        "returncode": returncode,
        "duration_seconds": duration,
        "peak_memory_bytes": peak_memory_bytes,
        "cpu_seconds": cpu_seconds,
        "incomplete_reporting": incomplete,
        "terminal_outcome": terminal_outcome,
        "captures": {
            "stdout": {
                "path": str(stdout_path),
                "artifact_id": stdout_artifact["artifact_id"],
                **public_stdout_state,
            },
            "stderr": {
                "path": str(stderr_path),
                "artifact_id": stderr_artifact["artifact_id"],
                **public_stderr_state,
            },
        },
        "artifact_sources": artifact_sources,
        "chunk_manifest": chunk_manifest,
    }
    payload = _json_bytes(result)
    descriptor_fd = os.open(
        result_path,
        os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0),
        0o600,
    )
    try:
        _write_all(descriptor_fd, payload)
        os.fsync(descriptor_fd)
    finally:
        os.close(descriptor_fd)
    return 0 if returncode == 0 and not incomplete else 1


def _json_bytes(value: object, *, maximum: int = MAX_RESULT_BYTES) -> bytes:
    payload = json.dumps(
        value, sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False
    ).encode("utf-8")
    if len(payload) > maximum:
        raise TestStoreContractError("runner result exceeds its bound")
    return payload


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="devcoordinator-test-runner")
    parser.add_argument("--launch", type=Path, required=True)
    arguments = parser.parse_args(argv)
    descriptor, output_root, result_path = _load(arguments.launch)
    return run(descriptor, output_root, result_path)


if __name__ == "__main__":
    raise SystemExit(main())
