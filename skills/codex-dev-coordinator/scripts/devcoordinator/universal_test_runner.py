def _load(path: Path) -> tuple[TestAttemptDescriptor, Path, Path]:
    metadata = path.lstat()
    if (
        not stat.S_ISREG(metadata.st_mode)
        or metadata.st_size > MAX_LAUNCH_BYTES
    ):
        raise TestStoreContractError("runner launch descriptor is unsafe")
    document = json.loads(path.read_bytes())
    base_fields = {
        "schema_version",
        "descriptor",
        "descriptor_fingerprint",
        "output_root",
        "result_path",
    }
    if not isinstance(document, Mapping):
        raise TestStoreContractError("runner launch descriptor fields are invalid")
    schema_version = document.get("schema_version")
    fields = set(document)
    if type(schema_version) is not int or (
        schema_version == 1 and fields != base_fields
    ) or (
        schema_version == 2 and fields != base_fields | {"launch_ticket_id"}
    ) or schema_version not in {1, 2}:
        raise TestStoreContractError("runner launch descriptor fields are invalid")
    if not isinstance(document["descriptor"], Mapping):
        raise TestStoreContractError("runner launch descriptor fields are invalid")
    if schema_version == 2:
        try:
            launch_ticket_id = _safe_id(
                "launch_ticket_id", document["launch_ticket_id"]
            )
        except TestStoreContractError as error:
            raise TestStoreContractError(
                "runner launch descriptor fields are invalid"
            ) from error
        if not launch_ticket_id.startswith("test-ticket-"):
            raise TestStoreContractError(
                "runner launch descriptor fields are invalid"
            )
    descriptor = TestAttemptDescriptor.from_document(document["descriptor"])
    if descriptor.fingerprint != document["descriptor_fingerprint"]:
        raise TestStoreContractError("runner launch descriptor fingerprint is invalid")
    if os.geteuid() != descriptor.owner_uid:
        raise TestStoreContractError("runner owner identity is invalid")
    result_path = Path(str(document["result_path"]))
    output_root = Path(str(document["output_root"]))
    try:
        output_metadata = output_root.lstat()
        resolved_output = output_root.resolve(strict=True)
    except OSError as error:
        raise TestStoreContractError("runner output root is unavailable") from error
    if (
        not output_root.is_absolute()
        or resolved_output != output_root
        or not stat.S_ISDIR(output_metadata.st_mode)
        or stat.S_ISLNK(output_metadata.st_mode)
        or result_path.parent != output_root
        or result_path.name != "result.json"
    ):
        raise TestStoreContractError("runner output boundary is unsafe")
    return descriptor, output_root, result_path


def _capture(stream, destination: Path, state: dict[str, object]) -> None:
    observed_digest = hashlib.sha256()
    retained_digest = hashlib.sha256()
    retained = 0
    total = 0
    truncated = False
    descriptor = os.open(
        destination,
        os.O_RDWR | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0),
        0o600,
    )
    state["_descriptor"] = descriptor
    output_descriptor = os.dup(descriptor)
    with os.fdopen(output_descriptor, "wb", buffering=0) as output:
        os.fchmod(descriptor, 0o600)
        while True:
            chunk = stream.read(64 * 1024)
            if not chunk:
                break
            total += len(chunk)
            observed_digest.update(chunk)
            if retained < MAX_CAPTURE_BYTES:
                keep = chunk[: MAX_CAPTURE_BYTES - retained]
                output.write(keep)
                retained_digest.update(keep)
                retained += len(keep)
            if total > MAX_CAPTURE_BYTES:
                truncated = True
        os.fsync(descriptor)
    identity = os.fstat(descriptor)
    state.update(
        {
            # ``sha256`` is the complete observed stream identity.  The
            # retained artifact has its own digest because a bounded capture
            # may be truncated.
            "sha256": observed_digest.hexdigest(),
            "retained_sha256": retained_digest.hexdigest(),
            "size_bytes": retained,
            "observed_bytes": total,
            "truncated": truncated,
            "device": identity.st_dev,
            "inode": identity.st_ino,
        }
    )


def _redact_capture_if_needed(path: Path, state: dict[str, object]) -> None:
    descriptor = state.get("_descriptor")
    if type(descriptor) is not int:
        raise TestStoreContractError("runner capture descriptor is unavailable")
    os.lseek(descriptor, 0, os.SEEK_SET)
    payload = os.read(descriptor, MAX_CAPTURE_BYTES + 1)
    if not _suspected_secret(payload):
        state["secret_redacted"] = False
        return
    replacement = b"[redacted: suspected secret material]\n"
    os.ftruncate(descriptor, 0)
    os.lseek(descriptor, 0, os.SEEK_SET)
    _write_all(descriptor, replacement)
    os.fsync(descriptor)
    state.update(
        {
            "retained_sha256": hashlib.sha256(replacement).hexdigest(),
            "size_bytes": len(replacement),
            "secret_redacted": True,
        }
    )


def _digest_private_file(
    path: Path,
    *,
    maximum_bytes: int,
    field: str,
) -> tuple[str, int]:
    descriptor = os.open(path, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0))
    try:
        before = os.fstat(descriptor)
        if (
            not stat.S_ISREG(before.st_mode)
            or before.st_size > maximum_bytes
        ):
            raise TestStoreContractError(f"{field} is unsafe")
        digest = hashlib.sha256()
        observed = 0
        tail = b""
        while True:
            chunk = os.read(descriptor, 1024 * 1024)
            if not chunk:
                break
            observed += len(chunk)
            if observed > maximum_bytes:
                raise TestStoreContractError(f"{field} exceeds its bound")
            digest.update(chunk)
            scan = tail + chunk
            if _suspected_secret(scan):
                raise TestStoreContractError(
                    f"{field} contains suspected secret material"
                )
            tail = scan[-4096:]
        after = os.fstat(descriptor)
        path_after = path.lstat()
        if (
            _stable_file_identity(before) != _stable_file_identity(after)
            or _stable_file_identity(after)
            != _stable_file_identity(path_after)
        ):
            raise TestStoreContractError(f"{field} changed during read")
        return digest.hexdigest(), observed
    finally:
        os.close(descriptor)


def _capture_artifact(
    descriptor: TestAttemptDescriptor,
    *,
    stream_name: str,
    path: Path,
    state: Mapping[str, object],
) -> Mapping[str, object]:
    """Publish one bounded capture through the typed artifact contract.

    The public handle is opaque and contains no server filesystem path.  The
    exact private path remains only in the broker-owned runner result envelope
    so a protected artifact collector can resolve it before attempt cleanup.
    """

    if stream_name not in {"stdout", "stderr"}:
        raise TestStoreContractError("capture artifact kind is invalid")
    metadata = path.lstat()
    retained_sha256 = state.get("retained_sha256")
    size_bytes = state.get("size_bytes")
    if (
        not stat.S_ISREG(metadata.st_mode)
        or stat.S_ISLNK(metadata.st_mode)
        or not isinstance(retained_sha256, str)
        or len(retained_sha256) != 64
        or type(size_bytes) is not int
        or size_bytes != metadata.st_size
        or size_bytes > MAX_CAPTURE_BYTES
        or (metadata.st_dev, metadata.st_ino)
        != (state.get("device"), state.get("inode"))
    ):
        raise TestStoreContractError("runner capture artifact is unsafe")
    artifact_id = "artifact-" + hashlib.sha256(
        (
            descriptor.attempt_id
            + "\0capture\0"
            + stream_name
            + "\0"
            + retained_sha256
        ).encode("utf-8")
    ).hexdigest()[:32]
    return {
        "artifact_id": artifact_id,
        "kind": "log",
        "storage_handle": f"test-artifact://{artifact_id}/{retained_sha256}",
        "sha256": retained_sha256,
        "size_bytes": size_bytes,
        "verified": True,
        "_source_path": str(path),
    }


def _contained(root: Path, relative: object) -> Path:
    if not isinstance(relative, str) or not relative or relative.startswith("/"):
        raise TestStoreContractError("runner artifact path is invalid")
    candidate = (root / relative).resolve(strict=True)
    if candidate != root and root not in candidate.parents:
        raise TestStoreContractError("runner artifact path escapes attempt root")
    return candidate


def _artifact(
    descriptor: TestAttemptDescriptor,
    root: Path,
    output: Path,
    policy: Mapping[str, object],
) -> Mapping[str, object] | None:
    try:
        path = _contained(root, policy["path"])
    except (OSError, TestStoreContractError):
        if policy["required"] is True:
            raise TestStoreContractError(
                f"required artifact is missing: {policy['name']}"
            )
        return None
    metadata = path.lstat()
    if policy["kind"] == "directory":
        if _suspected_secret(os.fsencode(str(policy["path"]))):
            raise TestStoreContractError(
                "runner directory artifact path contains secret material"
            )
        if not stat.S_ISDIR(metadata.st_mode) or stat.S_ISLNK(metadata.st_mode):
            raise TestStoreContractError("runner directory artifact is unsafe")
        archive_name = "directory-" + hashlib.sha256(
            (descriptor.attempt_id + "\0" + str(policy["name"])).encode("utf-8")
        ).hexdigest()[:32] + ".tar"
        archive_path = output / archive_name
        archive_path.unlink(missing_ok=True)
        archive_fd = os.open(
            archive_path,
            os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0),
            0o600,
        )
        try:
            with os.fdopen(os.dup(archive_fd), "wb", closefd=True) as destination:
                evidence = package_directory(
                    path,
                    destination,
                    expected_uid=os.geteuid(),
                    maximum_bytes=int(policy["max_bytes"]),
                    prohibited_sequences=_EXACT_SECRET_VARIANTS,
                )
                destination.flush()
            os.fsync(archive_fd)
        except Exception:
            archive_path.unlink(missing_ok=True)
            raise
        finally:
            os.close(archive_fd)
        artifact_id = "artifact-" + hashlib.sha256(
            (
                descriptor.attempt_id
                + "\0"
                + str(policy["name"])
                + "\0"
                + evidence.sha256
            ).encode("utf-8")
        ).hexdigest()[:32]
        return {
            "artifact_id": artifact_id,
            "kind": "directory",
            "storage_handle": f"test-artifact://{artifact_id}/{evidence.sha256}",
            "sha256": evidence.sha256,
            "size_bytes": evidence.size_bytes,
            "verified": True,
            "_source_path": str(archive_path),
            "_packaged_from_path": str(path),
        }
    if not stat.S_ISREG(metadata.st_mode) or stat.S_ISLNK(metadata.st_mode):
        raise TestStoreContractError("runner artifact is not a regular file")
    digest, size = _digest_private_file(
        path,
        maximum_bytes=int(policy["max_bytes"]),
        field=f"artifact {policy['name']}",
    )
    artifact_id = "artifact-" + hashlib.sha256(
        (
            descriptor.attempt_id
            + "\0"
            + str(policy["name"])
            + "\0"
            + digest
        ).encode("utf-8")
    ).hexdigest()[:32]
    return {
        "artifact_id": artifact_id,
        "kind": policy["kind"],
        "storage_handle": f"test-artifact://{artifact_id}/{digest}",
        "sha256": digest,
        "size_bytes": size,
        "verified": True,
        "_source_path": str(path),
    }


def _generated_artifact(
    descriptor: TestAttemptDescriptor,
    path: Path,
    *,
    kind: str,
    name: str,
) -> Mapping[str, object]:
    metadata = path.lstat()
    if (
        not stat.S_ISREG(metadata.st_mode)
        or stat.S_ISLNK(metadata.st_mode)
        or metadata.st_size > MAX_REPORT_BYTES
    ):
        raise TestStoreContractError("generated reporter artifact is unsafe")
    digest, observed_size = _digest_private_file(
        path,
        maximum_bytes=MAX_REPORT_BYTES,
        field="generated reporter artifact",
    )
    artifact_id = "artifact-" + hashlib.sha256(
        (descriptor.attempt_id + "\0" + name + "\0" + digest).encode("utf-8")
    ).hexdigest()[:32]
    return {
        "artifact_id": artifact_id,
        "kind": kind,
        "storage_handle": f"test-artifact://{artifact_id}/{digest}",
        "sha256": digest,
        "size_bytes": observed_size,
        "verified": True,
        "_source_path": str(path),
    }


def _directory_failure_diagnostic(
    descriptor: TestAttemptDescriptor,
    artifacts: Sequence[Mapping[str, object]],
    *,
    output: Path,
) -> Mapping[str, object] | None:
    """Project bounded text tails from already verified directory archives."""

    chunks: list[bytes] = []
    retained = 0
    allowed_suffixes = {".json", ".jsonl", ".log", ".txt", ".xml"}
    private_roots: dict[str, bytes] = {}
    for private_root, replacement in (
        (descriptor.original_root, b"<repository>"),
        (descriptor.execution_root, b"<execution-root>"),
        (descriptor.worktree_key, b"<worktree>"),
        (str(output), b"<attempt-output>"),
    ):
        private_roots.setdefault(str(Path(private_root)), replacement)
    if descriptor.temporary_root is not None:
        private_roots.setdefault(str(Path(descriptor.temporary_root)),
            b"<temporary-repository>"
        )
    for artifact in artifacts:
        if artifact.get("kind") != "directory":
            continue
        archive_text = artifact.get("_source_path")
        if not isinstance(archive_text, str):
            raise TestStoreContractError("runner directory artifact source is missing")
        archive = Path(archive_text)
        with tarfile.open(archive, mode="r:") as packaged:
            for member in packaged.getmembers():
                member_path = PurePosixPath(member.name)
                if (
                    not member.isfile()
                    or member.size <= 0
                    or member.size > MAX_REPORT_BYTES
                    or member_path.is_absolute()
                    or any(part in {".", ".."} for part in member_path.parts)
                    or member_path.suffix.lower() not in allowed_suffixes
                ):
                    continue
                source = packaged.extractfile(member)
                if source is None:
                    continue
                payload = source.read(MAX_REPORT_BYTES + 1)
                if len(payload) != member.size or b"\0" in payload:
                    continue
                tail = payload[-MAX_FAILURE_DIAGNOSTIC_FILE_BYTES:]
                for private_root, replacement in sorted(
                    private_roots.items(), key=lambda item: len(item[0]), reverse=True
                ):
                    tail = tail.replace(os.fsencode(private_root), replacement)
                text = tail.decode("utf-8", errors="replace")
                if text and (
                    sum(character.isprintable() or character in "\r\n\t" for character in text)
                    / len(text)
                ) < 0.85:
                    continue
                header = f"== {member_path.as_posix()} ==\n".encode("utf-8")
                candidate = header + tail + (b"" if tail.endswith(b"\n") else b"\n")
                available = MAX_FAILURE_DIAGNOSTIC_BYTES - retained
                if available <= 0:
                    break
                selected = candidate[:available]
                chunks.append(selected)
                retained += len(selected)
            if retained >= MAX_FAILURE_DIAGNOSTIC_BYTES:
                break
    if not chunks:
        return None
    path = output / "failure-diagnostics.log"
    path.write_bytes(b"".join(chunks))
    return _generated_artifact(
        descriptor,
        path,
        kind="log",
        name="failure-diagnostics",
    )


def _artifact_sources(
    artifacts: Sequence[Mapping[str, object]],
    *,
    output: Path,
    execution_root: Path,
) -> tuple[list[dict[str, object]], list[dict[str, object]]]:
    """Separate private collection paths from public exact-ID metadata."""

    public: list[dict[str, object]] = []
    sources: list[dict[str, object]] = []
    for raw in artifacts:
        value = dict(raw)
        source_text = value.pop("_source_path", None)
        packaged_from_text = value.pop("_packaged_from_path", None)
        if not isinstance(source_text, str):
            raise TestStoreContractError("runner artifact source is missing")
        source = Path(source_text)
        try:
            relative = source.relative_to(output)
            scope = "output"
        except ValueError:
            try:
                relative = source.relative_to(execution_root)
                scope = "execution"
            except ValueError as error:
                raise TestStoreContractError(
                    "runner artifact source escapes trusted roots"
                ) from error
        if not relative.parts or any(part in {".", ".."} for part in relative.parts):
            raise TestStoreContractError("runner artifact relative path is invalid")
        public.append(value)
        packaged_from: str | None = None
        if packaged_from_text is not None:
            if value.get("kind") != "directory" or not isinstance(packaged_from_text, str):
                raise TestStoreContractError("runner directory artifact source is invalid")
            try:
                packaged_from = Path(packaged_from_text).relative_to(execution_root).as_posix()
            except ValueError as error:
                raise TestStoreContractError(
                    "runner directory artifact source escapes execution root"
                ) from error
        sources.append(
            {
                "artifact_id": value["artifact_id"],
                "storage_handle": value["storage_handle"],
                "kind": value["kind"],
                "scope": scope,
                "relative_path": relative.as_posix(),
                "packaged_from": packaged_from,
                "sha256": value["sha256"],
                "size_bytes": value["size_bytes"],
            }
        )
    return public, sources


def adapt_driver_invocation(
    descriptor: TestAttemptDescriptor, output: Path
) -> tuple[tuple[str, ...], dict[str, str], Path, str]:
    """Return one fixed no-shell reporter adapter for the typed driver."""

    environment = dict(descriptor.environment)
    environment.update(
        {
            "DEVCOORDINATOR_TEST_SHARD_INDEX": str(descriptor.shard_index),
            "DEVCOORDINATOR_TEST_SHARD_COUNT": str(descriptor.shard_count),
        }
    )
    argv = tuple(descriptor.argv)
    is_dotnet_invocation = _is_dotnet_project_invocation(descriptor)
    if is_dotnet_invocation:
        # Apply the same trusted, attempt-local CLI state to a typed dotnet
        # test and to an automation target whose exact executable is dotnet.
        environment.update(
            {
                "DOTNET_CLI_HOME": str(output / "dotnet-cli-home"),
                "DOTNET_CLI_TELEMETRY_OPTOUT": "1",
                "DOTNET_NOLOGO": "1",
                "DOTNET_SKIP_FIRST_TIME_EXPERIENCE": "1",
                "DOTNET_CLI_WORKLOAD_UPDATE_NOTIFY_DISABLE": "1",
            }
        )
    if descriptor.driver == "pytest":
        reporter = output / "reporter.junit.xml"
        if descriptor.shard_count > 1:
            _publish_pytest_shard_plugin(output)
            inherited_pythonpath = environment.get("PYTHONPATH")
            environment["PYTHONPATH"] = str(output) + (
                "" if inherited_pythonpath is None else os.pathsep + inherited_pythonpath
            )
            argv += ("-p", "devcoordinator_pytest_shard")
        argv += ("--junitxml", str(reporter))
        kind = "junit"
    elif descriptor.driver == "dotnet":
        reporter = output / "reporter.trx"
        # A fresh attempt HOME must not turn every dotnet invocation into a
        # first-use/workload-maintenance operation.  Keep all mutable CLI state
        # inside the attempt output and make the non-test SDK behavior fixed by
        # the trusted adapter rather than repository-controlled environment.
        dotnet_arguments = argv[2:]
        passthrough = (
            dotnet_arguments.index("--")
            if "--" in dotnet_arguments
            else len(dotnet_arguments)
        )
        if (
            _dotnet_locked_restore_required(descriptor)
            and "--no-build" in dotnet_arguments[:passthrough]
        ):
            # Dependency targets run in separate immutable attempts; their
            # writable build output is deliberately not shared.  Let this
            # test attempt build from its already sealed offline restore.
            before_passthrough = tuple(
                argument
                for argument in dotnet_arguments[:passthrough]
                if argument != "--no-build"
            )
            dotnet_arguments = (
                *before_passthrough,
                *dotnet_arguments[passthrough:],
            )
            argv = (*argv[:2], *dotnet_arguments)
            passthrough = len(before_passthrough)
        trusted_options: tuple[str, ...] = ()
        if (
            _dotnet_locked_restore_required(descriptor)
            and "--no-restore" not in dotnet_arguments[:passthrough]
        ):
            # The trusted bootstrap below performs the exact offline locked
            # restore.  Project execution must not silently contact sources or
            # repeat audit/restore work afterward.
            trusted_options += ("--no-restore",)
        trusted_options += (
            "--logger",
            f"trx;LogFileName={reporter.name}",
            "--results-directory",
            str(output),
        )
        insertion = 2 + passthrough
        argv = (*argv[:insertion], *trusted_options, *argv[insertion:])
        kind = "trx"
    elif descriptor.driver == "node" and any(
        argument == "--test" or argument.startswith("--test=")
        for argument in argv[1:]
    ):
        reporter = output / "reporter.junit.xml"
        node_options = [
            "--test-reporter=junit",
            f"--test-reporter-destination={reporter}",
        ]
        if descriptor.shard_count > 1:
            node_options.append(
                "--test-shard="
                f"{descriptor.shard_index + 1}/{descriptor.shard_count}"
            )
        # Node stops parsing CLI options after the first positional test path.
        # Inject trusted reporter/shard options immediately after the executable
        # so repository-declared paths cannot turn them into file arguments.
        argv = (argv[0], *node_options, *argv[1:])
        kind = "junit"
    else:
        reporter = output / "reporter.events.jsonl"
        environment["DEVCOORDINATOR_TEST_EVENTS"] = str(reporter)
        environment["DEVCOORDINATOR_TEST_RESULTS"] = str(reporter)
        kind = "jsonl"
    return argv, environment, reporter, kind


