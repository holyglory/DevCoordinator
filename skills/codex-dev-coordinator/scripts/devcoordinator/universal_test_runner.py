def _stable_file_identity(metadata: os.stat_result) -> tuple[int, ...]:
    return (
        metadata.st_dev,
        metadata.st_ino,
        stat.S_IFMT(metadata.st_mode),
        metadata.st_size,
        metadata.st_mtime_ns,
        metadata.st_ctime_ns,
    )


def _write_all(descriptor: int, payload: bytes) -> None:
    """Write a complete bounded payload or fail without publishing it."""

    view = memoryview(payload)
    written = 0
    while written < len(view):
        count = os.write(descriptor, view[written:])
        if count <= 0:
            raise TestStoreContractError("runner result write did not make progress")
        written += count


def _suspected_secret(payload: bytes) -> bool:
    return _SECRET_MATERIAL.search(payload) is not None or any(
        material in payload for material in _EXACT_SECRET_VARIANTS
    )


def _credential_secret_variants(
    descriptor: TestAttemptDescriptor,
) -> tuple[bytes, ...]:
    if not descriptor.credentials:
        return ()
    raw_directory = os.environ.get("CREDENTIALS_DIRECTORY")
    if not raw_directory:
        raise TestStoreContractError("operational credential directory is unavailable")
    directory = Path(raw_directory)
    try:
        metadata = directory.lstat()
        resolved = directory.resolve(strict=True)
        entries = tuple(directory.iterdir())
    except OSError as error:
        raise TestStoreContractError(
            "operational credential directory is unavailable"
        ) from error
    if (
        not directory.is_absolute()
        or resolved != directory
        or not stat.S_ISDIR(metadata.st_mode)
        or stat.S_ISLNK(metadata.st_mode)
        or len(entries) > 64
    ):
        raise TestStoreContractError("operational credential directory is unsafe")
    directory_identity = _stable_file_identity(metadata)
    variants: set[bytes] = set()
    for path in entries:
        try:
            path_before = path.lstat()
        except OSError as error:
            raise TestStoreContractError(
                "operational credential material is unavailable"
            ) from error
        if (
            not stat.S_ISREG(path_before.st_mode)
            or stat.S_ISLNK(path_before.st_mode)
        ):
            raise TestStoreContractError(
                "operational credential material is unsafe"
            )
        try:
            descriptor_fd = os.open(
                path,
                os.O_RDONLY | os.O_CLOEXEC | getattr(os, "O_NOFOLLOW", 0),
            )
        except OSError as error:
            raise TestStoreContractError(
                "operational credential material is unavailable"
            ) from error
        try:
            before = os.fstat(descriptor_fd)
            if (
                not stat.S_ISREG(before.st_mode)
            ):
                raise TestStoreContractError(
                    "operational credential material is unsafe"
                )
            if not 16 <= before.st_size <= 64 * 1024:
                continue
            payload = bytearray()
            while True:
                chunk = os.read(descriptor_fd, 64 * 1024)
                if not chunk:
                    break
                payload.extend(chunk)
                if len(payload) > 64 * 1024:
                    raise TestStoreContractError(
                        "operational credential material is excessive"
                    )
            os.lseek(descriptor_fd, 0, os.SEEK_SET)
            verification = bytearray()
            while True:
                chunk = os.read(descriptor_fd, 64 * 1024)
                if not chunk:
                    break
                verification.extend(chunk)
                if len(verification) > 64 * 1024:
                    raise TestStoreContractError(
                        "operational credential material is excessive"
                    )
            after = os.fstat(descriptor_fd)
        finally:
            os.close(descriptor_fd)
        try:
            current = path.lstat()
        except OSError as error:
            raise TestStoreContractError(
                "operational credential material changed"
            ) from error
        if (
            _stable_file_identity(before) != _stable_file_identity(after)
            or _stable_file_identity(after) != _stable_file_identity(current)
            or _stable_file_identity(current)
            != _stable_file_identity(path_before)
            or payload != verification
        ):
            raise TestStoreContractError("operational credential material changed")
        value = bytes(payload)
        variants.update(
            {
                value,
                base64.b64encode(value),
                base64.urlsafe_b64encode(value).rstrip(b"="),
                value.hex().encode("ascii"),
            }
        )
    try:
        directory_after = directory.lstat()
    except OSError as error:
        raise TestStoreContractError(
            "operational credential directory changed"
        ) from error
    if directory_identity != _stable_file_identity(directory_after):
        raise TestStoreContractError(
            "operational credential directory changed"
        )
    if not variants:
        raise TestStoreContractError("operational credential material is unavailable")
    return tuple(sorted(variants, key=lambda value: (-len(value), value)))


